# -*- coding: utf-8 -*-
"""书库文本清洗的共享规则。

被两个模块共用，避免正则与映射表在门禁和修复工具之间漂移：

- ``tools/audit_library_quality.py`` —— 质量门禁（只检测，不修改）
- ``tools/repair_library_text.py`` —— 数据修复（按同一套规则删除/映射）

规则依据逐字节核查结论，见
``.workbuddy/artifacts/content-integrity-audit-2026-09-10.md``。
"""

from __future__ import annotations

import re

# 纯导航行：整行由导航词（可带括注）组合而成，例如
# "上一篇 回目录 下一篇"、"上一篇（德文本第一版序言） 回目录 下一篇（工业无产阶级）"
NAV_RE = re.compile(
    r"^(?:(?:上一篇|下一篇|回目录|返回目录|上一页|下一页|目录)\s*[（(]?[^）)]{0,30}[）)]?\s*)+$"
)

# 兜底：含"回目录"且很短的段落必定是导航行
NAV_MARK_RE = re.compile(r"回目录")

# 结构标题行：第N卷/篇/章/节/部 后接分隔空白。
# 源页面把卷/篇/章标题作为普通文本行输出，而 App 已用 chapter.title
# 单独渲染标题，正文再出现一次会造成视觉重复。
STRUCT_RE = re.compile(r"^第[一二三四五六七八九十百0-9]+(?:卷|篇|章|节|部)[\s　]")

# 结构标题行的最大长度（超过则视为正文语句，例如"在第三章里我们……"）
STRUCT_MAX_LEN = 32

# 章节开头 N 段内出现结构标题行即视为标题行
HEAD_WINDOW = 4

# 已确认可映射的源站损坏字符：Unicode 私有区（U+E000-U+F8FF）→ 原字符。
# 这些字节原本是全角空格、拉丁变音符或常用汉字，源站在历史编码转换中写坏了。
PUA_MAP: dict[str, str] = {
    "\ue4c6": "\u3000",  # 段首缩进（源页字节 A1 40，标准全角空格为 A1 A1）
    "\ue4e1": "\u3000",  # 同上，出现在脚注定义段首
    "\ue18c": "ö",        # Deutsch-Französische
    "\ue18d": "ä",        # Vorwärts / schlägt
    "\ue207": "志",       # "某些共同标志"
    "\ue40a": "米",       # "若干平方米"
}

# 曾被认为是"永久丢失"的源站损坏字符。
#
# 2026-09-10 复查推翻了原判断：这些 PUA 字符并不是信息丢失，而是源页把某个
# 汉字的首字节/次字节写成了 ASCII '?'(0x3F)，造成其后 GB 双字节整体错位，
# 错位解码才会落进私有区。重新对齐后可完整还原，真正的损失只有被 '?' 顶掉的
# 单个汉字。三处错位（043.htm@19185、043.htm@19210、044.htm@57147、
# 044.htm@57254、044.htm@72241）共 5 个字已通过"幸存字节 + 英文权威译本"
# 双重取证定案并修复，见 ``tools/repair_source_shift.py``。
#
# 因此本表清空：此后任何 PUA 字符都应视为 ERROR，而不是"已知损坏"。
PUA_UNRESOLVED: tuple[str, ...] = ()


def norm(value: str) -> str:
    """归一化：去掉所有空白字符，用于标题比对。"""
    return re.sub(r"\s+", "", value or "")
